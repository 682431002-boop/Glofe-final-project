/**
 * Generates database/seed.sql from the ORIGINAL product array in GloFe-New/app.js.
 *
 * Why a generator? So the seed is derived from your verified project file instead of
 * being retyped by hand. Only the two corrections you approved are applied (see
 * CORRECTIONS below); everything else is copied verbatim.
 *
 * Run (from repo root):  node database/tools/generate-seed.js
 * No npm packages are required.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..', '..');
const APP_JS = path.join(ROOT, 'GloFe-New', 'app.js');
const IMG_DIR = path.join(ROOT, 'GloFe-New');
const OUT = path.join(ROOT, 'database', 'seed.sql');

// ---- 1. Load the original PRODUCTS array exactly as written in app.js -------------
const src = fs.readFileSync(APP_JS, 'utf8');
const start = src.indexOf('const PRODUCTS = [');
const end = src.indexOf('\n];', start);
if (start < 0 || end < 0) throw new Error('Could not locate PRODUCTS array in app.js');
const arraySrc = src.slice(start + 'const PRODUCTS = '.length, end + 3);
const PRODUCTS = vm.runInNewContext('(' + arraySrc.replace(/;\s*$/, '') + ')');

// ---- 2. The ONLY changes to original data (approved by the project owner) ---------
const CORRECTIONS = {
  4: (p) => {
    p.sizes = undefined; // cap: no clothing sizes
    // Only the garment noun changed ("pullover" -> "cap"); all other words kept.
    p.desc = p.desc.replace('pullover', 'cap');
  },
  13: (p) => {
    // Fear of God Essentials is a clothing item (T-shirt in the image).
    // Tag order matches the other clothing products (#4, #6, #10): Clothing first.
    p.tags = ['Clothing', 'Fashion'];
  },
};
const original = JSON.parse(JSON.stringify(PRODUCTS));
for (const p of PRODUCTS) if (CORRECTIONS[p.id]) CORRECTIONS[p.id](p);

// ---- 3. Helpers ------------------------------------------------------------------
const MONTHS = { Jan:1, Feb:2, Mar:3, Apr:4, May:5, Jun:6, Jul:7, Aug:8, Sep:9, Oct:10, Nov:11, Dec:12 };
function parseDeadline(s) {
  const m = /^(\d{1,2}) ([A-Z][a-z]{2}) (\d{4})$/.exec(s);
  if (!m || !MONTHS[m[2]]) throw new Error('Unrecognised deadline: ' + s);
  return `${m[3]}-${String(MONTHS[m[2]]).padStart(2, '0')}-${m[1].padStart(2, '0')}`;
}
// MySQL string literal escaping (backslash, quote, control chars)
const q = (v) => {
  if (v === null || v === undefined) return 'NULL';
  return "'" + String(v)
    .replace(/\\/g, '\\\\').replace(/'/g, "\\'")
    .replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\0/g, '\\0') + "'";
};
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// ---- 4. Countries & categories ---------------------------------------------------
// Origin countries come from the products. Shipping destinations come from the
// checkout page (payment.html): TH, MY, SG, ID, BN.
const COUNTRIES = [
  // id, code, name, flag, is_origin, is_shipping_destination
  [1, 'KR', 'Korea',     '🇰🇷', 1, 0],
  [2, 'JP', 'Japan',     '🇯🇵', 1, 0],
  [3, 'CN', 'China',     '🇨🇳', 1, 0],
  [4, 'US', 'USA',       '🇺🇸', 1, 0],
  [5, 'TH', 'Thailand',  '🇹🇭', 0, 1],
  [6, 'MY', 'Malaysia',  '🇲🇾', 0, 1],
  [7, 'SG', 'Singapore', '🇸🇬', 0, 1],
  [8, 'ID', 'Indonesia', '🇮🇩', 0, 1],
  [9, 'BN', 'Brunei',    '🇧🇳', 0, 1],
];
const countryId = Object.fromEntries(COUNTRIES.map((c) => [c[2], c[0]]));
// Sanity check: the flag in app.js must match our countries table.
for (const p of PRODUCTS) {
  const c = COUNTRIES.find((x) => x[2] === p.country);
  if (!c || c[3] !== p.flag) throw new Error(`Country/flag mismatch for product ${p.id}`);
}

// Categories = distinct tags, ordered by first appearance. Primary category = first tag.
const tagOrder = [];
for (const p of PRODUCTS) for (const t of p.tags) if (!tagOrder.includes(t)) tagOrder.push(t);
const categoryId = Object.fromEntries(tagOrder.map((t, i) => [t, i + 1]));

// ---- 5. Verify every image file exists (catches Thai filename problems early) ----
const missing = PRODUCTS.map((p) => p.image).filter((f) => !fs.existsSync(path.join(IMG_DIR, f)));
if (missing.length) throw new Error('Missing image files: ' + missing.join(', '));

// ---- 6. Emit SQL -----------------------------------------------------------------
const out = [];
out.push(`-- ============================================================================
-- GloFe seed data  (GENERATED by database/tools/generate-seed.js - do not hand-edit)
-- Source: GloFe-New/app.js (original product array).
--
-- Approved corrections applied (everything else is verbatim from app.js):
--   #4  CAP MARDI BOLD LOGO_BROWN CREAM : clothing sizes S-XL removed;
--       description noun "pullover" -> "cap".
--       ORIGINAL: ${q(original.find((p) => p.id === 4).desc)}
--   #13 FEAR OF GOD ESSENTIALS          : tags ['Fashion','Shoes'] -> ['Clothing','Fashion'];
--       sizes S/M/L/XL kept.
--
-- Not in the original data, therefore left NULL (not invented): brand, estimated_arrival,
-- stock_quantity. shipping_fee is 0.00 until you configure real fees.
-- Import with:  mysql --default-character-set=utf8mb4 -u root glofe < database/seed.sql
-- ============================================================================
SET NAMES utf8mb4;
`);

out.push('INSERT INTO countries (id, code, name, flag_emoji, is_origin, is_shipping_destination, shipping_fee) VALUES');
out.push(COUNTRIES.map((c) => `  (${c[0]}, ${q(c[1])}, ${q(c[2])}, ${q(c[3])}, ${c[4]}, ${c[5]}, 0.00)`).join(',\n') + ';\n');

out.push('INSERT INTO categories (id, name, slug) VALUES');
out.push(tagOrder.map((t) => `  (${categoryId[t]}, ${q(t)}, ${q(slug(t))})`).join(',\n') + ';\n');

out.push('INSERT INTO products (id, name, description, price, currency, country_id, category_id, tags, is_preorder, preorder_deadline, is_active) VALUES');
out.push(PRODUCTS.map((p) =>
  `  (${p.id}, ${q(p.name)}, ${q(p.desc)}, ${Number(p.price).toFixed(2)}, 'THB', ${countryId[p.country]}, ${categoryId[p.tags[0]]}, ${q(JSON.stringify(p.tags))}, 1, ${q(parseDeadline(p.deadline))}, 1)`
).join(',\n') + ';\n');

out.push('INSERT INTO product_images (product_id, image_path, alt_text, sort_order, is_primary) VALUES');
out.push(PRODUCTS.map((p) => `  (${p.id}, ${q(p.image)}, ${q(p.name)}, 0, 1)`).join(',\n') + ';\n');

const variantRows = [];
for (const p of PRODUCTS) (p.sizes || []).forEach((s, i) => variantRows.push(`  (${p.id}, 'Size', ${q(s)}, ${i})`));
out.push('INSERT INTO product_variants (product_id, option_name, option_value, sort_order) VALUES');
out.push(variantRows.join(',\n') + ';\n');

fs.writeFileSync(OUT, out.join('\n'), 'utf8');
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${PRODUCTS.length} products, ${tagOrder.length} categories, ${variantRows.length} variants.`);
